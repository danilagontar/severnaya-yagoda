describe("итог в свободной форме", () => {
  it("«К оплате 130 руб.» при 10 × 12 = 120 — вернуть (П-8)", () => {
    const { r } = run(KS, "Счёт 34 по ЗП-14: прокладка картонная 1200х800, 10 шт. по 12 руб. К оплате 130 руб.");
    expect(r.ex.total).toBe(130);
    expect(r.verdict).toBe("return");
  });
  it("«15.000,00 руб.» — тысячи через точку", () => {
    const { r } = run(PL, "Счёт 202 по ЗП-06: пакет 300 г, 5000 шт. по 3,00 руб. Итого 15.000,00 руб.");
    expect(r.ex.total).toBe(15000);
  });
  it("«120 (сто двадцать) руб.» — сумма прописью в скобках", () => {
    const { r } = run(KS, "Счёт 34 по ЗП-14: прокладка картонная, 10 шт. по 12 руб. Итого 120 (сто двадцать) руб.");
    expect(r.ex.total).toBe(120);
  });
  it("цена «4.40» по-прежнему читается как 4,40", () => {
    const { r } = run(PL, "Счёт 215 по ЗП-13: пакет для ягод 500 г, 1000 шт. по 4.40 руб. Итого 4 400 руб.");
    expect(r.ex.price).toBe(4.4);
  });
});
