import { describe, expect, it } from "vitest";
import data from "../data/case.json";
import { reconcileAll } from "./reconcile";
import type { CaseData, Letter } from "./types";

const D = data as CaseData;
const PL = "«Пакетная линия», invoice@paketline.example";
const LP = "«Лентапром», schet@lentaprom.example";
const EN = "«Этикетка-Норд», buh@etiketka-nord.example";
const KS = "«Картон-Сервис», buh@karton-servis.example";
const BUYER = "Анна Ковалёва, закупщик, a.kovaleva@sev-yagoda.example";

function run(sender: string, text: string) {
  const l: Letter = { id: "Н-01", received: "16.11 12:30", sender, text };
  const all = reconcileAll(D, [...D.letters, l], undefined, new Set(["Н-01"]));
  return { r: all.find((x) => x.id === "Н-01")!, get: (id: string) => all.find((x) => x.id === id)! };
}

describe("реквизиты: «стоп» только на смену, а не на любое упоминание", () => {
  it("«реквизиты для оплаты указаны в счёте» — не стоп", () => {
    const { r } = run(PL, "Счёт 206 по ЗП-11: пакет-вкладыш 600×800 мм, 100 шт. по 7 руб. Итого 700 руб. Реквизиты для оплаты указаны в счёте.");
    expect(r.ex.requisitesChange).toBe(false);
    expect(r.verdict).not.toBe("stop");
  });
  it("«реквизиты прежние, ничего не менялось» — письмо, не стоп", () => {
    const { r } = run(PL, "По счёту 205: подтверждаем, реквизиты прежние, ничего не менялось.");
    expect(r.verdict).toBe("letter");
  });
  it("настоящая смена реквизитов по-прежнему стоп", () => {
    const { r } = run(PL, "По счёту 205: обращаем внимание, реквизиты изменились, оплату просим на р/с 40702810500000000999.");
    expect(r.verdict).toBe("stop");
  });
  it("ответ над цитатой: новые реквизиты упомянуты только в цитате — не стоп", () => {
    const { r } = run(PL, "Подтверждаем, реквизиты прежние, ничего не менялось.\n\n> Добрый день, у вас сменился банк? Пришло письмо о новых реквизитах.");
    expect(r.verdict).not.toBe("stop");
  });
});

describe("пересланные письма", () => {
  it("закупщик пересылает новый счёт поставщика — это счёт поставщика, а не комментарий", () => {
    const { r } = run(
      BUYER,
      "Пересылаю счёт, прошу оплатить.\n\n---------- Пересланное сообщение ----------\nОт: «Пакетная линия» <invoice@paketline.example>\nСчёт 211 по ЗП-11: пакет-вкладыш 600×800 мм, 100 шт. по 7 руб. Итого 700 руб.",
    );
    expect(r.ex.kind).toBe("invoice");
    expect(r.supplier).toBe("Пакетная линия");
    expect(r.orderId).toBe("ЗП-11");
    expect(r.findings.some((f) => /переслан/i.test(f.text))).toBe(true);
  });
  it("закупщик пересылает уже полученный счёт — дубль", () => {
    const { r } = run(
      BUYER,
      "Пересылаю счёт от поставщика, прошу оплатить.\n\n---------- Пересланное сообщение ----------\nОт: «Пакетная линия» <invoice@paketline.example>\nСчёт 202 по ЗП-06: пакет 300 г, 5000 шт. по 3,00 руб. Итого 15 000 руб.",
    );
    expect(r.verdict).toBe("duplicate");
    expect(r.duplicateOf).toBe("В-02");
  });
  it("старый счёт в цитате не мешает новому сверху", () => {
    const { r } = run(
      "«Гофроцентр Волхов», sales@gofro-volhov.example",
      "Высылаем счёт 121 по ЗП-01: гофрокороб 400х300х250, 200 шт. по 40 руб. Итого 8 000 руб.\n\n-----Original Message-----\nОт: Олег Смирнов\n> Счёт 116 по ЗП-01: гофрокороб 4-клапанный 400х300х250, 1000 шт. по 40 руб. Итого 40 000 руб.",
    );
    expect(r.ex.invoiceNo).toBe("121");
    expect(r.duplicateOf).toBe("В-23");
  });
  it("счёт только в цитате ответа: повторная отправка, исходного нет — проверяем как новый", () => {
    const { r } = run(EN, "Когда ждать оплату?\n\n> 14.11.2026 «Этикетка-Норд» пишет:\n> Счёт 140 по ЗП-07: термоэтикетка 100×150, 2 рулона по 1000 шт., цена рулона 1500 руб. Итого 3 000 руб.");
    expect(r.ex.kind).toBe("copy");
    expect(r.ex.asksPaymentDate).toBe(true);
    expect(r.verdict).toBe("ask");
  });
});

describe("несколько счетов в одном письме", () => {
  it("два счёта по одному заказу — вопрос, второй не теряется молча", () => {
    const { r } = run(
      EN,
      "Направляем два счёта по ЗП-07: счёт 125 — 2 рулона по 1000 шт., цена рулона 1500 руб., итого 3 000 руб.; счёт 126 — 1 рулон по 1000 шт., цена рулона 1500 руб., итого 1 500 руб.",
    );
    expect(r.verdict).toBe("ask");
    expect(r.ex.otherInvoices).toEqual(["126"]);
    expect(r.findings.some((f) => f.level === "ask" && f.text.includes("126"))).toBe(true);
  });
  it("копии двух счетов по разным заказам — вопрос, а не «дубль» только первого", () => {
    const { r } = run(PL, "Счёт 202 по ЗП-06: пакет 300 г, 5000 шт. по 3 руб. Итого 15 000 руб.\nСчёт 205 по ЗП-11: пакет-вкладыш, 2000 шт. по 7 руб. Итого 14 000 руб.");
    expect(r.verdict).toBe("ask");
    expect(r.payNow).toBe(0);
    expect(r.findings.some((f) => f.text.includes("205"))).toBe(true);
  });
  it("«счета 125 и 126» перечислением — видны оба номера", () => {
    const { r } = run(EN, "Просим оплатить счета 125 и 126 по ЗП-07 на общую сумму 4 500 руб.");
    expect(r.ex.otherInvoices).toEqual(["126"]);
    expect(r.findings.some((f) => f.text.includes("126"))).toBe(true);
  });
});

