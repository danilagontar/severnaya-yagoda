import type { Result, Verdict } from "./types";

export interface TrapExpect {
  verdict: Verdict[];
  payNow?: number; // сумма в реестр (для «оплатить»)
  due?: number; // «должно быть» по сверке (для «вопроса»)
  orderId?: string | null;
  duplicateOf?: string | null; // null: дублем быть не должно
  check?: (r: Result, get: (id: string) => Result) => string | null; // доп. проверка: текст ошибки или null
}

export interface TrapLetter {
  id: string;
  group: string;
  trap: string;
  sender: string;
  text: string;
  expect: TrapExpect;
}

